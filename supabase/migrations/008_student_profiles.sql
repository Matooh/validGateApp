  profile_id,
  student_id,
  institution_id
)
select
  p.id,
  s.id,
  coalesce(p.institution_id, s.institution_id)
from public.profiles p
join public.students s
  on s.institution_id = p.institution_id
 and lower(trim(s.first_name)) = lower(trim(p.first_name))
 and lower(trim(s.last_name)) = lower(trim(p.last_name))
where p.email = 'alan.estudiante@validgate.app'
  and p.role = 'ESTUDIANTE'
  and p.institution_id is not null
on conflict do nothing;

